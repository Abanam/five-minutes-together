"""Write app/sw-files.js: the list of every file the service worker caches, plus a
version hash of their contents (a new hash makes phones download the update).
Run after any change to app/:   python tools/build_sw_list.py"""
import hashlib
import json
from pathlib import Path

APP = Path(__file__).resolve().parents[1] / "app"
SKIP = {"sw.js", "sw-files.js", ".nojekyll"}

files, h = [], hashlib.sha256()
for p in sorted(APP.rglob("*")):
    if not p.is_file() or p.name in SKIP or p.name.startswith("_"):
        continue
    if p.relative_to(APP).parts[0] == "v1.0":  # the archived v1.0 is not part of the v1.1 offline cache
        continue
    rel = p.relative_to(APP).as_posix()
    files.append(rel)
    h.update(rel.encode())
    h.update(p.read_bytes())
version = h.hexdigest()[:12]
files = ["./"] + files
(APP / "sw-files.js").write_text(
    "// Generated by tools/build_sw_list.py – do not edit by hand.\n"
    f"self.FMT_VERSION = '{version}';\n"
    f"self.FMT_FILES = {json.dumps(files, indent=0)};\n",
    encoding="utf-8")
size = sum((APP / f).stat().st_size for f in files if f != "./")
print(f"sw-files.js: {len(files)} entries, version {version}, {size / 1024 / 1024:.2f} MB to cache")
